import { CLAUSE_BY_ID } from './clause-schema.mjs'

const BYPASS_FORMULA_SLUGS = new Set(['b-trust', 'clayton-qtip', 'disclaimer'])
for (const [slug, coverage] of Object.entries(CLAUSE_COVERAGE)) {
  if (coverage.C20 == null) {
    coverage.C20 = BYPASS_FORMULA_SLUGS.has(slug) ? 'typical' : 'no'
  }
}

/**
 * @param {string} slug
 * @returns {{ id: string, label: string, value: CoverageValue, group: 'clause' | 'attribute' }[]}
 */
export function clauseRowsForSlug(slug) {
  const coverage = CLAUSE_COVERAGE[slug]
  if (!coverage) return []

  return Object.entries(coverage).map(([id, value]) => {
    const def = CLAUSE_BY_ID.get(id)
    return {
      id,
      label: def?.label ?? id,
      value,
      group: def?.group ?? (id.startsWith('A') ? 'attribute' : 'clause'),
    }
  })
}
